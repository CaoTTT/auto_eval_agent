CALIBRATION_RULES = r"""
【执行补充：按本轮需求核对有效缺陷及六维独立影响】
以下细化六维的执行方式；原表全文、Gate、适用性、核验及空分规则保持不变。
可评分维度按第四节从5分起评，只有有效缺陷才扣分。以下不增加新的满分准入条件。

一、先确定当前需要完成什么
1. 根据Query和该产品自身有效上下文，判断主要目的、明确条件和有依据的隐含需求。
   区分分享、轻松互动、倾诉、安慰、分析、方法和话术；多种目的并存时判断主次。
   用户未说明、且有效上下文也无依据支持的目标、情绪、经历和后续任务，不能成为必须完成的条件。
2. 内部区分本轮必要回应与可选增强。必要回应由当前需求和本维相关锚点共同确定；
   多给方案、细节、选项、背景引用或新颖措辞，只有确实服务当前需求才有评价价值。
   分享和陪伴不强制分析或行动方案；明确求方法时仍须有可用帮助，不用安慰替代方法。
3. 关键歧义影响方向时，必要、简洁的澄清可以是恰当回应；信息足够时不能用追问回避回答。
   回答主动引入的偏题、误导、越界和额外负担，仍按原标准评价。
   正向子项未触发不等于整个维度不适用，适用性沿用原规则。

二、评分前核对事实与来源
1. 声称“未回应、没有、缺少”前，完整阅读目标轮相关图文并核对语义等价内容。
   区分确实缺失、已有但不足、材料无法确认。已有候选方向、示例或倾听回应，不能记作完全没有。
   认定不足须说明还缺什么、为何本轮需要，以及可由材料判断的影响。
   复制文本冲突按原视觉证据优先级处理；不能猜测隐藏内容或未提供的交互过程。
2. 保留主语、对象、否定、条件、时序和确定程度。区分祝愿、可能性、询问与事实断言或保证。
   条件词和问号不自动免责；开头或结尾一句正确表达也不能抵消中间的矛盾和越界。
3. 区分采集时间、评测运行时间与用户明确的事件时间。时间地点本身不独立证明活动、生日、习惯或经历。
   产品自述不独立证明历史真实；未提供来源也不单独证明编造。
   关键来源缺失时只限制真正依赖它的维度，其他可判断表现继续评分。
   若已提供材料中的关键指代仍有多种解释，回复却将某一解释及额外经历作为确定事实，
   应评价实际可见的擅自补全风险，不能因安慰充分就忽略理解与情感边界。
4. 先逐产品按同一绝对尺度从5分检查扣分项，再比较；允许不同表达同获高分或同分。
   另一产品多给内容，不构成本产品必需内容的证明。不能为了选出唯一最佳回答而压低其余产品。

三、先核对维度职责，再判断不足的影响
1. 理解需求：评价是否识别正确的目的、重点、条件和指代，以及必要的歧义处理。
   回答较短、没有展开或引导较泛，不单独证明理解浅；须指出究竟误解或遗漏了什么已有诉求。
2. 场景化满足：评价回应是否满足本轮实际需要。分享得到自然接话、倾诉得到合适陪伴，
   可以满足本轮需求；不能要求用户没有请求的方法和步骤。求方法、方案或话术时，
   则应核对当前必要的可用内容，确实缺失时不能以“这是闲聊”免除。
3. 情感表达恰当：评价有依据的情绪承接、时机、强度、尊重和边界。
   “具体”是贴合已有信息，不是细节多或感情浓。中性与轻松交流不强求深度安慰；
   常见亲切语句不自动是模板或装熟。认定机械、错位或亲密越界，须说明本轮实际缺口。
   不能通过补造经历、无依据认定或夸大用户感受、保证无法保证的结果换取共情高分。
4. 风格恰当：按本轮复杂度核对长度、口语、语气、排版及附加内容造成的真实负担。
   Emoji、列表、常见开场或短句本身不决定档位；方法任务中清楚的列表可能合适，
   普通分享中长篇分析可能打断节奏。仅见一轮不能断言跨轮机械套用。
5. 引导推荐：核对相关性、时机、推进价值、可回应性和负担，评价整段回答。
   开放式、二选一、给出猜测后要提示等形式本身不加减分。开放问题贴合当前情境时可以高分；
   二选一若无依据、限制用户或重复已知信息，也可能不佳。
   用户仍需自然接话、选择话题或补充感受，不等于当前回应尚不可用；
   但缺乏情境关联、把确有必要的开场责任全交回用户，可以构成引导不足，须说明具体负担。
   不能仅凭这一项引导不足，联动认定理解、共情和风格全部不足。
   无引导需求且未引导时按原规则不适用；已结束的核心需求不应为了拿高分而强行延伸。
6. 个性化适配：沿用原适用性，内部依次核对信息是否为该产品可知、是否影响本轮回应、
   使用或遗漏是否产生实际适配影响。相关且有效的本轮用户条件也属于可适配信息；
   关闭记忆不等于没有当前条件，裁判知道的信息也不等于产品知道。
   已知时间地点但与当前目的无关，不构成必须使用；未显式提及背景不等于未适配。
   若本轮确需根据相关条件调整，而回答仍停留在表面复述、遗漏必要适配、误用信息或表达生硬，
   按原表相应缺陷及实际影响扣分。不以缺少额外亮点作为扣分依据，机械插入时间地点也不另加分。
   无相关需求且未使用个人信息时不适用；主动使用、强行关联或明确编造时仍须评价。
7. 同一证据影响多维时，分别写明“本维要求—实际缺口—本维影响”。
   例如冗长可影响风格；只有确实改变需求方向、削弱必要帮助或打断情绪时，
   才进一步影响理解、场景或情感。不能复制“通用、略浅、像模板”作为多维共同结论。

四、简短边界校对
1. 用户分享“终于能休息一天”：回应这份开心并问如何安排休息，若无实际缺陷则维持相关维度5分；
   不必强制列两个活动选项。仍需逐维检查实际扣分项，不能因某一维表现合适就跳过其他维度检查。
2. 用户求陪聊：接受陪伴、允许表达或暂不表达，理解与情感没有实际缺陷时保留5分；
   是否提供了足够低负担的开场，再独立判断场景与引导，不能仅因一句“想聊什么”把五维都判低。
3. 用户只想吐槽却收到长篇原因分析，或用户明确求办法却只有泛泛安慰，仍按原标准评价不足。
4. 用户明确结束交流：尊重结束本身符合相关需求；没有必要引导且未引导时返回不适用，
   不为凑整数分强制给3或5，也不奖励无依据地补出“要睡觉、要忙了”等原因。

五、输出前复核
逐产品检查每个已扣分维度是否具有可定位缺陷、当前需求依据、本维实际影响及相称的扣分幅度。
凡以“通用、较浅、推进有限、模板”为依据，再次核实真实缺口，不能只凭标签扣分。
扣分依据不成立时撤销相应扣分并重新核对综合影响；证据足够且没有剩余有效扣分项时保留5分。
禁止为维持原低分补造问题，也禁止因材料缺失而未经核验直接给5分。
决定性证据不足继续执行原核验规则，不用中间分代替无法判断。
上述步骤仅用于内部核对。依据写入现有reason，每产品通常1—3句，先写本产品证据和表现，
再说明扣分项、实际影响及最终分数；未扣分时简述检查依据和本轮无有效扣分项。
不输出需求分类、子项分、缺陷清单或自检过程。
仍保持原有六维JSON键、类型、顺序及双/三产品输出合同，不增加字段。
"""


VISUAL_COMPARE_SYSTEM = Template(
    RULES
    + "\n" + CALIBRATION_RULES
    + "\n【完整原表锚点与案例】\n"
    + SOURCE_ANCHORS
    + "\n【本次完整输出模板】\n"
      "以下示例只展示字段、类型和顺序。pass和3仅为形状示例，不能照抄；"
      "必须按本题证据独立选择Gate、分数或null。\n"
      "{{ output_example(product_count) }}"
)
VISUAL_COMPARE_SYSTEM.globals["output_example"] = output_example


def render_system_prompt(
    *, product_count: int = 2, evidence_mode: str = "long_screenshot", persona: str = ""
) -> str:
    """Render only the new variant; existing chat V2 templates stay untouched."""
    if type(product_count) is not int or product_count not in (2, 3):
        raise ValueError("product_count must be 2 or 3")
    if evidence_mode not in ("long_screenshot", "video_frames"):
        raise ValueError("unknown evidence_mode")
    return VISUAL_COMPARE_SYSTEM.render(
        persona=persona, product_count=product_count, evidence_mode=evidence_mode
    )
