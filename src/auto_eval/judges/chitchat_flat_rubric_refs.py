def render_rubric_references() -> str:
    lines = [
        "【原表子项索引：reason引用依据】",
        "以下定位ID由本提示词按原表子项顺序编制，用于查找原文，不是新增评分标准。",
        "来源为《对话问答评测标准-闲聊标准.xlsx》/聊天评测标准。响应、安全为门槛原文；其余提供原表1/3/5分子项。",
        "原文锚点需结合本轮需求和完整上下文使用；不能只凭‘通用、轻微、略’等词机械套档。",
        "前文防误判说明、2/4分插值和后文reason格式属于执行解释，不能冒充原表逐字规定。",
    ]
    for key, item in RUBRIC_REFERENCES.items():
        cells = "/".join(item["source_cells"])
        lines.append(f"[{key} {item['name']}]（单元格{cells}，子项{item['source_item']}）")
        lines.extend(f"  {grade}：{text}" for grade, text in item["anchors"].items())
    return "\n".join(lines) + "\n"
