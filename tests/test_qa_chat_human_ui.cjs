const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/auto_eval/web/static/human-compare.js'),'utf8').replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,'');
const context={ref:v=>({value:v}),computed:f=>({get value(){return f();}}),onUnmounted(){},AbortController,DOMException,URLSearchParams,FormData,setTimeout,clearTimeout};
vm.runInNewContext(source+'\nthis.Panel=HumanComparePanel;',context);
const panel=context.Panel.setup({taskId:'chat-task'});
panel.templateStandard.value='qa_chat_compare@1.0';
assert.equal(Object.keys(panel.baselineDimensions.value).length,6,'without a baseline the chat template displays six chat dimensions');
assert.ok(!('service_closure' in panel.baselineDimensions.value));
panel.templateStandard.value='0.3';
assert.ok('service_closure' in panel.baselineDimensions.value,'without a baseline the legacy template retains legacy dimensions');
panel.baselines.value=[{baseline_id:'hb_chat',version:1,human_standard_id:'qa_chat_compare',products:[]}];
panel.baselineKey.value='hb_chat:1';panel.baselineChanged();
assert.equal(panel.selectedDimensions.value.length,6);
assert.equal(Object.keys(panel.baselineDimensions.value).join(','),'understanding,personalization,emotional_expression,style,scenario_fulfillment,guided_recommendation');
panel.baselines.value.push({baseline_id:'hb_frozen',version:1,human_standard_id:'qa_competitor_compare',dimension_names:{understanding:'冻结需求标签'},products:[]});
panel.baselineKey.value='hb_frozen:1';panel.templateStandard.value='qa_chat_compare@1.0';
assert.equal(Object.keys(panel.baselineDimensions.value).length,1,'selected baseline dimensions override the template selector');
assert.equal(panel.baselineDimensions.value.understanding,'冻结需求标签');
panel.baselineKey.value='hb_chat:1';
assert.ok(panel.standards.some(([id])=>id==='qa_chat_compare@1.0'));
panel.mapping.value={human_standard_id:'qa_competitor_compare',human_standard_version:'0.3',human_bundle_revision:'0.3.1',products:[{product_id:'p1'}],labels:[]};
panel.changeMappingStandard('qa_chat_compare@1.0');
assert.equal(panel.mapping.value.human_standard_id,'qa_chat_compare');
assert.equal(panel.mapping.value.human_standard_version,'1.0');
assert.equal(panel.mapping.value.human_bundle_revision,'');
assert.equal(panel.mappingStandard(),'qa_chat_compare@1.0');
assert.equal(Object.keys(panel.mappingDimensions.value).length,6);
assert.ok(!('accuracy' in panel.mappingDimensions.value));
panel.addLabel();
assert.equal(panel.mapping.value.labels[0].applicable,'');
assert.equal(panel.mapping.value.labels[0].verification_status,'');
panel.changeMappingStandard('0.3');
assert.equal(panel.mapping.value.human_standard_id,'qa_competitor_compare');
assert.ok('accuracy' in panel.mappingDimensions.value);
assert.match(context.Panel.template,/baselineDimensions/);
assert.match(context.Panel.template,/产品适用性列/);
assert.match(context.Panel.template,/核验状态列/);
assert.match(context.Panel.template,/输入失败排除/);
console.log('QA-chat human UI: six dynamic dimensions, explicit protocol family, blank state mapping and old-family isolation passed');
