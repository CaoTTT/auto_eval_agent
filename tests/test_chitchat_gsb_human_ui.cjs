const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/auto_eval/web/static/human-compare.js'),'utf8').replace(/^import[^\n]*\n/gm,'').replace(/^export /gm,'');
const context={ref:v=>({value:v}),computed:f=>({get value(){return f();}}),onUnmounted(){},AbortController,DOMException,URLSearchParams,FormData,setTimeout,clearTimeout};
vm.runInNewContext(source+'\nthis.Panel=HumanComparePanel;',context);
const profile='chitchat_gsb_compare@1.0';
const panel=context.Panel.setup({taskId:'gsb-task',evaluationProfile:profile});
assert.equal(panel.templateStandard.value,profile);
assert.deepEqual(Array.from(panel.selectedDimensions.value),['overall']);
assert.ok(panel.standards.some(s=>s[0]===profile));
assert.equal(panel.baselineDimensions.value.overall,'整体GSB');
panel.mapping.value={products:[{product_id:'p1'},{product_id:'p2'}],labels:[{score:'A'}]};
panel.changeMappingStandard(profile);
assert.equal(panel.mappingIsGSB.value,true);
assert.equal(panel.mapping.value.labels.length,0);
assert.equal(panel.mapping.value.human_bundle_revision,'1.0.0');
assert.equal(panel.mapping.value.human_result_schema_version,'chitchat-gsb-result-1');
panel.addPairLabel();
assert.equal(panel.mapping.value.pair_labels.length,1);
assert.equal(panel.mapping.value.pair_labels[0].product_a,'p1');
assert.equal(panel.mapping.value.pair_labels[0].product_b,'p2');
assert.equal(panel.mapping.value.pair_labels[0].gsb,'');
assert.equal(panel.mappingStandard(),profile);
panel.baselines.value=[{baseline_id:'hb',version:1,human_standard_id:'chitchat_gsb_compare',score_dimensions:[],products:[{product_id:'p1',display_name:'甲'},{product_id:'p2',display_name:'乙'}]}];
panel.baselineKey.value='hb:1';panel.baselineChanged();
assert.deepEqual(Array.from(panel.selectedDimensions.value),['overall']);
panel.report.value={human_protocol:{human_standard_id:'chitchat_gsb_compare'},metrics:{gsb_agreement:[{product_id:'pair',product_a:'p1',product_b:'p2',scope:'own'},{product_id:'pair',product_a:'p1',product_b:'p2',scope:'common'}]}};
assert.equal(panel.reportIsGSB.value,true);
assert.equal(panel.visibleGSB.value.length,1);
assert.equal(panel.gsbPairs.value.length,1);
assert.equal(panel.pname('pair'),'甲 / 乙');
assert.match(context.Panel.template,/GSB完全一致率/);
assert.match(context.Panel.template,/G与B反向率/);
assert.match(context.Panel.template,/mapping\.pair_labels/);
assert.match(context.Panel.template,/r\.human_gsb/);
assert.match(context.Panel.template,/r\.model_gsb/);
assert.match(context.Panel.template,/!reportIsGSB/);
assert.match(context.Panel.template,/showEvidence\(r,side\)/);
panel.changeMappingStandard('0.2-simplified');
assert.equal(panel.mappingIsGSB.value,false);
assert.equal(panel.mapping.value.pair_labels.length,0);
assert.ok(panel.mappingDimensions.value.understanding);
console.log('GSB human UI: categorical mapping, frozen identity, pair agreement, reversal and legacy isolation passed');
